"""Input/Output routines, molecule loaders, format converters, and JCAMP-DX exporter."""

import os
from typing import Optional, Tuple, Dict, Any, List
from rdkit import Chem
from rdkit.Chem import AllChem
import numpy as np


def load_molecule(
    smiles: Optional[str] = None,
    xyz_path: Optional[str] = None,
    mol_path: Optional[str] = None,
    mol_block: Optional[str] = None,
    xyz_block: Optional[str] = None
) -> Tuple[Chem.Mol, str, str]:
    """Loads a molecule from various inputs and returns: (rdkit_mol_with_hydrogens, xyz_string, canonical_smiles).
    
    Generates 3D coordinates using ETKDGv3 if molecule has no 3D conformer.
    """
    mol: Optional[Chem.Mol] = None
    xyz_str: str = ""

    if smiles:
        mol = Chem.MolFromSmiles(smiles)
        if mol is None:
            raise ValueError(f"SMILES non valido: '{smiles}'")
        mol = Chem.AddHs(mol)
        # Generate initial 3D conformer if not present
        params = AllChem.ETKDGv3()
        params.randomSeed = 42
        conf_id = AllChem.EmbedMolecule(mol, params)
        if conf_id < 0:
            AllChem.EmbedMolecule(mol, useRandomCoords=True)
        try:
            AllChem.MMFFOptimizeMolecule(mol)
        except Exception:
            pass
        xyz_str = mol_to_xyz(mol)

    elif mol_block:
        if "\n" not in mol_block:
            mol = Chem.MolFromSmiles(mol_block.strip())
        else:
            mol = Chem.MolFromMolBlock(mol_block, removeHs=False)
            if mol is None:
                mol = Chem.MolFromMolBlock(mol_block.strip(), removeHs=False)
            if mol is None and not mol_block.startswith("\n"):
                mol = Chem.MolFromMolBlock("\n" + mol_block, removeHs=False)
                
        if mol is None:
            mol = Chem.MolFromSmiles(mol_block.strip())
            if mol is None:
                raise ValueError("Struttura molecolare / MolBlock non valido.")
                
        mol = Chem.AddHs(mol)
        
        # Check if coordinates are 2D planar (all z ~ 0) or missing
        needs_3d = False
        if mol.GetNumConformers() == 0:
            needs_3d = True
        else:
            conf = mol.GetConformer()
            if all(abs(conf.GetAtomPosition(i).z) < 1e-4 for i in range(mol.GetNumAtoms())):
                needs_3d = True
                
        if needs_3d:
            params = AllChem.ETKDGv3()
            params.randomSeed = 42
            conf_id = AllChem.EmbedMolecule(mol, params)
            if conf_id < 0:
                AllChem.EmbedMolecule(mol, useRandomCoords=True)
            try:
                AllChem.MMFFOptimizeMolecule(mol)
            except Exception:
                pass
                
        xyz_str = mol_to_xyz(mol)

    elif mol_path:
        if not os.path.isfile(mol_path):
            raise FileNotFoundError(f"File MOL/SDF non trovato: {mol_path}")
        if mol_path.lower().endswith(".sdf"):
            suppl = Chem.SDMolSupplier(mol_path, removeHs=False)
            mol = next(suppl, None)
        else:
            mol = Chem.MolFromMolFile(mol_path, removeHs=False)
        if mol is None:
            raise ValueError(f"Impossibile leggere file MOL: {mol_path}")
        mol = Chem.AddHs(mol)
        if mol.GetNumConformers() == 0:
            AllChem.EmbedMolecule(mol, AllChem.ETKDGv3())
        xyz_str = mol_to_xyz(mol)

    elif xyz_path or xyz_block:
        content = xyz_block
        if xyz_path:
            if not os.path.isfile(xyz_path):
                raise FileNotFoundError(f"File XYZ non trovato: {xyz_path}")
            with open(xyz_path, "r", encoding="utf-8") as f:
                content = f.read()
        
        xyz_str = content.strip()
        mol = xyz_to_rdkit_mol(xyz_str)
    else:
        raise ValueError("Nessun input fornito (fornire SMILES, file XYZ o file MOL).")

    canonical_smiles = Chem.MolToSmiles(Chem.RemoveHs(mol))
    return mol, xyz_str, canonical_smiles


def mol_to_xyz(mol: Chem.Mol, conf_id: int = -1) -> str:
    """Converts an RDKit Mol object into a standard XYZ formatted string."""
    conf = mol.GetConformer(conf_id)
    n_atoms = mol.GetNumAtoms()
    lines = [f"{n_atoms}", "Molecule generated by nmr-inator"]
    for i in range(n_atoms):
        atom = mol.GetAtomWithIdx(i)
        pos = conf.GetAtomPosition(i)
        lines.append(f"{atom.GetSymbol():<2} {pos.x:12.6f} {pos.y:12.6f} {pos.z:12.6f}")
    return "\n".join(lines)


def parse_xyz(xyz_str: str) -> Tuple[List[str], np.ndarray]:
    """Parses an XYZ string into atomic symbols and numpy coordinates array (N, 3)."""
    lines = [line.strip() for line in xyz_str.strip().splitlines() if line.strip()]
    if not lines:
        return [], np.zeros((0, 3))
    
    # Check if first line is atom count
    start_idx = 0
    if lines[0].isdigit():
        start_idx = 2  # skip count and comment line
        
    symbols = []
    coords = []
    for line in lines[start_idx:]:
        parts = line.split()
        if len(parts) >= 4:
            symbols.append(parts[0])
            coords.append([float(parts[1]), float(parts[2]), float(parts[3])])
            
    return symbols, np.array(coords, dtype=np.float64)


def xyz_to_rdkit_mol(xyz_str: str) -> Chem.Mol:
    """Reconstructs an RDKit Mol with 3D conformation and inferred connectivity from XYZ."""
    symbols, coords = parse_xyz(xyz_str)
    if len(symbols) == 0:
        raise ValueError("Stringa XYZ vuota o non valida.")
        
    raw_mol = Chem.RWMol()
    conf = Chem.Conformer(len(symbols))
    from rdkit.Geometry import Point3D
    
    for i, sym in enumerate(symbols):
        atom = Chem.Atom(sym)
        idx = raw_mol.AddAtom(atom)
        conf.SetAtomPosition(idx, Point3D(coords[i, 0], coords[i, 1], coords[i, 2]))
        
    raw_mol.AddConformer(conf, assignId=True)
    
    # Use RDKit's rdDetermineBonds if available, or fall back to distance-based connectivity
    try:
        from rdkit.Chem import rdDetermineBonds
        mol_copy = raw_mol.GetMol()
        rdDetermineBonds.DetermineBonds(mol_copy)
        return mol_copy
    except Exception:
        # Fallback using distance heuristics
        mol = raw_mol.GetMol()
        mol = Chem.AddHs(mol, addCoords=True)
        return mol


def export_to_jcamp_dx(
    spectrum_type: str,  # "NMR" or "IR"
    title: str,
    x_axis: List[float],
    y_axis: List[float],
    nucleus: Optional[str] = "1H",
    frequency_mhz: Optional[float] = 400.0,
    solv_name: Optional[str] = None
) -> str:
    """Exports spectrum data to the international JCAMP-DX standard file format (v5.01).
    Compatible with MestreNova, TopSpin, ACD/Spectrus, and open spectral viewers.
    """
    if len(x_axis) == 0 or len(y_axis) == 0:
        return ""
        
    lines = [
        "##TITLE= " + title,
        "##JCAMP-DX= 5.01",
        f"##DATA TYPE= {'NMR SPECTRUM' if spectrum_type.upper() == 'NMR' else 'INFRARED SPECTRUM'}",
        "##ORIGIN= nmr-inator Quantum Spectroscopy Suite",
        "##OWNER= Generated by nmr-inator",
    ]
    
    if spectrum_type.upper() == "NMR":
        lines.extend([
            f"##.OBSERVE NUCLEUS= {nucleus}",
            f"##.OBSERVE FREQUENCY= {frequency_mhz:.4f}",
            f"##XUNITS= PPM",
            f"##YUNITS= ARBITRARY UNITS",
        ])
    else:
        lines.extend([
            "##XUNITS= 1/CM",
            "##YUNITS= % TRANSMITTANCE",
        ])
        
    if solv_name:
        lines.append(f"##SOLVENT NAME= {solv_name}")
        
    min_x = min(x_axis)
    max_x = max(x_axis)
    min_y = min(y_axis)
    max_y = max(y_axis)
    n_points = len(x_axis)
    
    lines.extend([
        f"##FIRSTX= {x_axis[0]:.4f}",
        f"##LASTX= {x_axis[-1]:.4f}",
        f"##FIRSTY= {y_axis[0]:.4f}",
        f"##NPOINTS= {n_points}",
        f"##MINX= {min_x:.4f}",
        f"##MAXX= {max_x:.4f}",
        f"##MINY= {min_y:.4f}",
        f"##MAXY= {max_y:.4f}",
        "##XYDATA= (X++(Y..Y))"
    ])
    
    # Write XY points
    for x, y in zip(x_axis, y_axis):
        lines.append(f"{x:10.4f}  {y:12.4f}")
        
    lines.append("##END=")
    return "\n".join(lines)

